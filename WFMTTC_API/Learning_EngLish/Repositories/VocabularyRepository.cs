using System.Data;
using Learning_EngLish.Data;
using Learning_EngLish.DTOs;
using Microsoft.Data.SqlClient;

namespace Learning_EngLish.Repositories;

/// <summary>
/// All SQL for the Vocabulary table lives here. The pattern for every method is:
///   1. open a connection        (await using -> closed automatically)
///   2. create a SqlCommand       (SQL text + connection)
///   3. add parameters            (NEVER concatenate user input into SQL -> SQL injection)
///   4. execute:
///        ExecuteReaderAsync    -> many rows (SELECT)
///        ExecuteScalarAsync    -> one single value (e.g. a new ID)
///        ExecuteNonQueryAsync  -> number of rows affected (UPDATE / DELETE)
/// </summary>
public class VocabularyRepository
{
    private readonly SqlConnectionFactory _db;

    public VocabularyRepository(SqlConnectionFactory db)
    {
        _db = db;
    }

    // Shared SELECT: joins the lookup tables so we can return names, not just IDs.
    private const string SelectSql = """
        SELECT v.VocabularyId, v.Word, v.Meaning,
               v.WordTypeId, w.Name AS WordTypeName,
               v.TopicId,    t.Name AS TopicName
        FROM Vocabulary v
        INNER JOIN WordType w ON w.WordTypeId = v.WordTypeId
        INNER JOIN Topic t    ON t.TopicId    = v.TopicId
        """;

    /// <summary>List vocabularies, optionally filtered by topic, word type and a search text.</summary>
    public async Task<List<VocabularyResponse>> GetAllAsync(int? topicId, int? wordTypeId, string? search)
    {
        // "@X IS NULL OR column = @X" means: if the filter is not given, ignore it.
        const string sql = SelectSql + """

            WHERE (@TopicId    IS NULL OR v.TopicId    = @TopicId)
              AND (@WordTypeId IS NULL OR v.WordTypeId = @WordTypeId)
              AND (@Search     IS NULL OR v.Word LIKE '%' + @Search + '%' OR v.Meaning LIKE '%' + @Search + '%')
            ORDER BY v.Word
            """;

        await using var connection = await _db.OpenAsync();
        await using var command = new SqlCommand(sql, connection);
        command.Parameters.Add("@TopicId", SqlDbType.Int).Value = (object?)topicId ?? DBNull.Value;
        command.Parameters.Add("@WordTypeId", SqlDbType.Int).Value = (object?)wordTypeId ?? DBNull.Value;
        command.Parameters.Add("@Search", SqlDbType.NVarChar, 100).Value =
            string.IsNullOrWhiteSpace(search) ? DBNull.Value : search.Trim();

        var result = new List<VocabularyResponse>();
        await using var reader = await command.ExecuteReaderAsync();
        while (await reader.ReadAsync())
        {
            result.Add(Map(reader));
        }
        return result;
    }

    public async Task<VocabularyResponse?> GetByIdAsync(int id)
    {
        const string sql = SelectSql + "\nWHERE v.VocabularyId = @Id";

        await using var connection = await _db.OpenAsync();
        await using var command = new SqlCommand(sql, connection);
        command.Parameters.Add("@Id", SqlDbType.Int).Value = id;

        await using var reader = await command.ExecuteReaderAsync();
        return await reader.ReadAsync() ? Map(reader) : null;
    }

    /// <summary>Inserts a row and returns the new VocabularyId (generated by the IDENTITY column).</summary>
    public async Task<int> CreateAsync(VocabularyRequest request)
    {
        // OUTPUT INSERTED.<col> returns values from the row that was just inserted.
        const string sql = """
            INSERT INTO Vocabulary (Word, Meaning, WordTypeId, TopicId)
            OUTPUT INSERTED.VocabularyId
            VALUES (@Word, @Meaning, @WordTypeId, @TopicId)
            """;

        await using var connection = await _db.OpenAsync();
        await using var command = new SqlCommand(sql, connection);
        AddRequestParameters(command, request);

        return (int)(await command.ExecuteScalarAsync())!;
    }

    /// <summary>Returns false when no row has that id.</summary>
    public async Task<bool> UpdateAsync(int id, VocabularyRequest request)
    {
        const string sql = """
            UPDATE Vocabulary
            SET Word = @Word, Meaning = @Meaning, WordTypeId = @WordTypeId, TopicId = @TopicId
            WHERE VocabularyId = @Id
            """;

        await using var connection = await _db.OpenAsync();
        await using var command = new SqlCommand(sql, connection);
        command.Parameters.Add("@Id", SqlDbType.Int).Value = id;
        AddRequestParameters(command, request);

        return await command.ExecuteNonQueryAsync() > 0;
    }

    /// <summary>Returns false when no row has that id.</summary>
    public async Task<bool> DeleteAsync(int id)
    {
        const string sql = "DELETE FROM Vocabulary WHERE VocabularyId = @Id";

        await using var connection = await _db.OpenAsync();
        await using var command = new SqlCommand(sql, connection);
        command.Parameters.Add("@Id", SqlDbType.Int).Value = id;

        return await command.ExecuteNonQueryAsync() > 0;
    }

    private static void AddRequestParameters(SqlCommand command, VocabularyRequest request)
    {
        command.Parameters.Add("@Word", SqlDbType.NVarChar, 100).Value = request.Word.Trim();
        command.Parameters.Add("@Meaning", SqlDbType.NVarChar, 500).Value = request.Meaning.Trim();
        command.Parameters.Add("@WordTypeId", SqlDbType.Int).Value = request.WordTypeId;
        command.Parameters.Add("@TopicId", SqlDbType.Int).Value = request.TopicId;
    }

    // Reads the current row by column name and turns it into a DTO.
    private static VocabularyResponse Map(SqlDataReader reader) => new(
        reader.GetInt32(reader.GetOrdinal("VocabularyId")),
        reader.GetString(reader.GetOrdinal("Word")),
        reader.GetString(reader.GetOrdinal("Meaning")),
        reader.GetInt32(reader.GetOrdinal("WordTypeId")),
        reader.GetString(reader.GetOrdinal("WordTypeName")),
        reader.GetInt32(reader.GetOrdinal("TopicId")),
        reader.GetString(reader.GetOrdinal("TopicName")));
}
